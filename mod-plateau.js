function applyModifierPlateauLocal(structure, w) {
    // ВАРИАНТ А: СИНДРОМ ПЕРЕТРЕНИРОВАННОСТИ ЦНС (Жесткий силовой деload)
    if (userContext.plateau === "plateau_over") {
        structure.disclaimerText += "\n\n🥵 [ВНИМАНИЕ: СИСТЕМА ПЕРЕТРЕНА ЦНС АКТИВИРОВАНА]: Выявлен глубокий застой нервной системы. Калькулятор принудительно включил разгрузочный микроцикл (Деload) — рабочие веса во всех базовых упражнениях снижены ровно на 50% от твоих исходных максимумов для восстановления рецепторов и связок!";
        
        structure.days.forEach(day => {
            day.exercises.forEach(ex => {
                if (ex.slot.includes("base")) {
                    // Силой срезаем веса наполовину, убирая старые текстовые килограммы
                    ex.weight = "СБРОС 50% (Легкий вес)";
                    ex.rir = "RIR 4 (Запрет отказов)";
                }
            });
        });
    }
    
    // ВАРИАНТ Б: СИНДРОМ НЕДОТРЕНИРОВАННОСТИ (Жесткий форсаж и дожим объемов)
    else if (userContext.plateau === "plateau_under") {
        structure.disclaimerText += "\n\n🥱 [УВЕДОМЛЕНИЕ: СИНДРОМ НЕДОТРЕНИРОВАННОСТИ]: Обнаружен застой из-за недостаточного стимула. В программу принудительно вшит шоковый протокол АТАК — во всех финальных подходах базы и подсобки RIR снижен до абсолютного нуля (Жесткий мышечный отказ)!";
        
        structure.days.forEach(day => {
            day.exercises.forEach(ex => {
                ex.rir = "<b>RIR 0 (АБСОЛЮТНЫЙ ОТКАЗ)</b>";
                ex.sets = "4"; // Форсируем объем до 4 подходов
            });
        });
    }
    return structure;
}
