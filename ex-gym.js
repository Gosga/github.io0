function getGymExercise(slotType, spineHealthy) {
    // Внутренний рандомизатор для выбора между конкурирующими движениями (50/50)
    let pick = function(ex1, ex2) {
        return Math.random() <= 0.5 ? ex1 : ex2;
    };

    // Жесткий медицинский перехват Георгия: если спина БЕЗ ОСЕВОЙ — убираем опасную базу!
    if (spineHealthy === "no") {
        if (slotType === "exPrised") return "Жим ногами в тренажере + Сгибания ног сидя (Безопасно для спины)";
        if (slotType === "exBic") return "Подъем гантелей на бицепс на скамье Скотта (Спина изолирована)";
        if (slotType === "exRow") return pick("Тяга Т-грифа с упором в грудь", "Тяга горизонтального блока к поясу");
        if (slotType === "exTraps") return "Шраги в тренажёре сидя/упоре";
    }
    // Пул для здоровой спины с 50% рандомизацией конкурирующих упражнений тренера
    const exercises = {
        exJim: pick("Жим штанги лежа на горизонтальной скамье", "Жим гантелей лежа на горизонтальной скамье"),
        exJimLight: pick("Жим штанги под углом 30 градусов (Легкий)", "Жим гантелей под углом 30 градусов (Объемный)"),
        exRow: pick("Тяга штанги к поясу в наклоне", "Тяга гантелей к поясу в наклоне"),
        exPrised: pick("Приседания со штангой на плечах", "Фронтальные приседания со штангой"),
        exBic: pick("Подъем штанги на бицепс стоя", "Подъем гантелей на бицепс с супинацией стоя"),
        exTri: pick("Разгибания рук на блоке с косичкой", "Разгибания рук с гантелью из-за головы сидя"),
        exDelt: pick("Разведения гантелей стоя (Махи)", "Протяжка штанги вдоль туловища к подбородку"),
        exCalves: pick("Подъемы на икры стоя в тренажере", "Подъемы на икры сидя в тренажере (Камбаловидная)"),
        exTraps: pick("Шраги со штангой стоя", "Шраги с тяжелыми гантелями стоя")
    };

    // Твои новые целевые изолирующие упражнения на квадрицепс и бицепс бедра
    if (slotType === "iso_legs") return "Разгибания ног в тренажере (Изоляция квадрицепса)";
    if (slotType === "iso_legs_alt") return "Сгибания ног в тренажере лежа (Изоляция бицепса бедра)";

    return exercises[slotType] || "Упражнение в зале";
}
console.log("💪 [БАЗА ЗАЛА v4.1]: Финальный реестр упражнений успешно собран.");
