function applyModifierSpineLocal(structure) {
    if (userContext.spine === "no") {
        console.log("⚠️ [КОНВЕЙЕР]: Режим «Без осевой нагрузки» активен. Перехват траекторий...");
        
        structure.days.forEach(day => {
            day.exercises.forEach(ex => {
                // Если при грыжах/протрузиях прорвался слот бицепса стоя — силой меняем на Скотта!
                if (ex.slot.includes("bic")) {
                    ex.name = "Подъем гантелей/штанги на бицепс на скамье Скотта (Спина изолирована)";
                    ex.icon = "🪙";
                    ex.note = "Замена: подъем стоя исключен для защиты поясницы ✅";
                }
                // Перехват тяги к поясу в наклоне
                if (ex.name.includes("Тяга штанги к поясу в наклоне") || ex.name.includes("Тяга гантелей к поясу в наклоне")) {
                    ex.name = "Тяга Т-грифа с упором в грудь (или тяга горизонтального блока сидя)";
                    ex.icon = "⚙️";
                    ex.note = "Замена: исключена нагрузка на поясничный столб ✅";
                }
                // Перехват трапеций (Шраги со штангой стоя уходят)
                if (ex.slot === "traps") {
                    ex.name = "Шраги в тренажере сидя или с упором грудью на скамье";
                    ex.icon = "🪵";
                }
            });
        });
    }
    return structure;
}
console.log("✅ [МОДУЛЬ СПИНЫ]: Запрет бицепса стоя и интеграция скамьи Скотта зафиксированы в mod-spine.js");
